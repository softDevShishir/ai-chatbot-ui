import { useId, type FormEvent, type KeyboardEvent, type Ref } from 'react'
import type { ProviderId } from '../api/types'

export const MAX_MESSAGE_CHARS = 2000

export type ProviderChoice = 'default' | ProviderId

const PROVIDER_OPTIONS: { value: ProviderChoice; label: string }[] = [
  { value: 'default', label: 'Default' },
  { value: 'claude', label: 'Claude' },
  { value: 'gemini', label: 'Gemini' },
  { value: 'openai', label: 'OpenAI' },
]

interface ComposerProps {
  value: string
  onChange: (value: string) => void
  onSend: (text: string) => void
  provider: ProviderChoice
  onProviderChange: (provider: ProviderChoice) => void
  busy: boolean
  inputRef?: Ref<HTMLTextAreaElement>
}

export function Composer({ value, onChange, onSend, provider, onProviderChange, busy, inputRef }: ComposerProps) {
  const id = useId()
  const counterId = `${id}-counter`
  const hintId = `${id}-hint`
  const length = value.length
  const canSend = !busy && value.trim().length > 0 && length <= MAX_MESSAGE_CHARS

  function submit(event?: FormEvent) {
    event?.preventDefault()
    if (canSend) onSend(value)
  }

  function handleKeyDown(event: KeyboardEvent<HTMLTextAreaElement>) {
    // Enter sends, Shift+Enter inserts a newline. Ignore Enter while an IME is composing text.
    if (event.key === 'Enter' && !event.shiftKey && !event.nativeEvent.isComposing) {
      event.preventDefault()
      submit()
    }
  }

  return (
    <form className="composer" onSubmit={submit} aria-label="Send a message">
      <div className="composer-toolbar">
        <label htmlFor={`${id}-provider`} className="composer-label">
          AI provider
        </label>
        <select
          id={`${id}-provider`}
          value={provider}
          onChange={(event) => onProviderChange(event.target.value as ProviderChoice)}
        >
          {PROVIDER_OPTIONS.map((option) => (
            <option key={option.value} value={option.value}>
              {option.label}
            </option>
          ))}
        </select>
        <span id={counterId} className={`char-counter${length >= MAX_MESSAGE_CHARS ? ' at-limit' : ''}`}>
          {length} / {MAX_MESSAGE_CHARS}
        </span>
      </div>
      <div className="composer-row">
        <label htmlFor={`${id}-message`} className="sr-only">
          Message
        </label>
        <textarea
          id={`${id}-message`}
          ref={inputRef}
          rows={2}
          maxLength={MAX_MESSAGE_CHARS}
          placeholder="Ask about products, delivery, returns…"
          value={value}
          onChange={(event) => onChange(event.target.value)}
          onKeyDown={handleKeyDown}
          aria-describedby={`${counterId} ${hintId}`}
        />
        <button type="submit" className="btn btn-primary send-btn" disabled={!canSend}>
          {busy ? 'Sending…' : 'Send'}
        </button>
      </div>
      <p id={hintId} className="composer-hint small muted">
        Enter to send, Shift+Enter for a new line.
      </p>
      <p className="ai-note">
        Replies are generated by AI and can be wrong. For important matters, ask for a support person.
      </p>
    </form>
  )
}
